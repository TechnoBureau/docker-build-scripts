#!/usr/bin/env bash

# Resolve current package versions from the build repositories and cache them
# to .cache/rpm-versions.yml. Used instead of lockfiles to compute version
# tags (e.g. 8.21.0) at Containerfile/TAGS generation time.
# Non-hermetic by design: versions are resolved from the repositories baked
# into the builder image at generation time.

set -euo pipefail
# inherit_errexit requires bash 4.4+; keep behavior on older bash (e.g. macOS 3.2)
if [[ ${BASH_VERSINFO[0]} -gt 4 ]] || { [[ ${BASH_VERSINFO[0]} -eq 4 && ${BASH_VERSINFO[1]} -ge 4 ]]; }; then
    shopt -s inherit_errexit
fi

cd "$(dirname "${BASH_SOURCE[0]}")/.."

BUILDER_IMAGE=${BUILDER_IMAGE:-quay.io/hummingbird-ci/hummingbird-builder:latest}
# Container engine used to run dnf repoquery; the CI driver exports the
# detected engine (podman or docker) at the call site.
CONTAINER_ENGINE=${CONTAINER_ENGINE:-podman}
CACHE_FILE=".cache/rpm-versions.yml"

mkdir -p .cache

# Collect all string packages from every rpms.in.yaml (python3 avoids a yq dependency)
# WHY: Distro-agnostic glob (images/<group>/<distro>/<variant>/rpms/rpms.in.yaml):
# ubi builds (HB_DISTROS=ubi9) have no hummingbird trees, and all distros resolve
# versions from the same builder-image repos.
packages=$(python3 - <<'EOF'
import pathlib
import sys
import yaml

pkgs = set()
for path in pathlib.Path("images").glob("*/[!.]*/*/rpms/rpms.in.yaml"):
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    for item in data.get("packages", []):
        if isinstance(item, str):
            pkgs.add(item)
print(" ".join(sorted(pkgs)))
EOF
)
if [[ -z ${packages} ]]; then
    echo "No packages found in images/*/rpms/rpms.in.yaml" >&2
    exit 1
fi

# Query latest versions from the repos baked into the builder image.
# %{EVR} output gets mangled by dnf5 in containers, so compose VERSION-RELEASE
# explicitly (epochs are stripped below anyway).
TMPFILE=$(mktemp)
trap 'rm -f "${TMPFILE}"' EXIT
# shellcheck disable=SC2086  # intentional word splitting for dnf package args
if ! "${CONTAINER_ENGINE}" run --rm "${BUILDER_IMAGE}" \
    dnf repoquery --quiet --latest-limit=1 --queryformat '%{NAME} %{VERSION}-%{RELEASE}\n' ${packages} 2>/dev/null \
    > "${TMPFILE}"; then
    echo "dnf repoquery failed; is the builder image available?" >&2
    exit 1
fi
readarray -t versions < "${TMPFILE}"

if [[ ${#versions[@]} -eq 0 ]]; then
    echo "dnf repoquery returned no results; is the builder image available?" >&2
    exit 1
fi

{
    echo "# Generated by ci/get_rpm_versions.sh - do not edit manually"
    echo "# Epochs are stripped; version tags are computed from these versions."
    for line in "${versions[@]}"; do
        line=${line%$'\r'}
        name=${line%% *}
        evr=${line#* }
        if [[ ${evr} == *:* ]]; then
            evr=${evr#*:}
        fi
        if [[ -n ${name} ]]; then
            printf '%s: %s\n' "${name}" "${evr}"
        fi
    done
} > "${CACHE_FILE}"

echo "Wrote ${CACHE_FILE}"
